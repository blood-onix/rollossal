def strings_module(objects) -> str:
    entries = {}
    for index, (en, es) in enumerate(TIER_NAMES, 1):
        entries[f"tier.park.{index}.name"] = {"en": en, "es": es}
        entries[f"tier.park.{index}.headline"] = {"en": TIER_HEADLINES[index - 1][0], "es": TIER_HEADLINES[index - 1][1]}
    for obj in objects:
        kind = obj["id"]
        if kind not in ES:
            raise SystemExit(f"no Spanish name for {kind}")
        entries[f"object.park.{kind}"] = {"en": english_name(kind), "es": ES[kind]}
    # Theme-only copies (the winter Plaza tree) carry their own names; the CityKit memes use the kit's strings.
    for theme in dress.SUPPORTED_THEMES:
        for oid, spec in dress.THEME_ONLY.get(theme, {}).items():
            if "copyOf" in spec:
                entries[f"object.park.{oid}"] = {"en": spec["en"], "es": spec["es"]}
    return (
        HEADER
        + "-- Names of the Park City kinds and tiers. The Spanish names are a first pass for owner review\n"
        + "-- (docs/release-candidate.md). Merged into Strings.luau.\n"
        + "--!nonstrict\n\n"
        + "return " + lua(entries) + "\n"
    )


def coverage_report(layout, objects, stages, catalogue, parts, light) -> tuple[str, str]:
    """coverage.json and coverage.md (R-02): every kind's status as this stage builds it, the totals and the owner's
    build list (stand-ins by placements x (7 - tier), placed kinds only)."""
    placements: dict[str, int] = {o["id"]: 0 for o in objects}
    for row in parts + light:
        placements[row["kind"]] += 1
    kinds = []
    for obj in objects:
        kind = obj["id"]
        planned = dress.DRESS[kind]
        look = effective_dress(kind, stages)
        key = planned.get("assetKey")
        scale = dress.scale_of(catalogue, key, obj["dims"]) if key else None
        note = planned["note"]
        if scale is not None and not dress.SCALE_MIN <= scale <= dress.SCALE_MAX:
            note = (note + "; " if note else "") + f"scale {scale} is outside {dress.SCALE_MIN} to {dress.SCALE_MAX}: " \
                "a stand-in candidate"
        if key and scale is None:
            note = (note + "; " if note else "") + "fit unchecked (no native size in a catalogue)"
        record = {"id": kind, "tier": obj["tier"], "placements": placements[kind], "status": look["status"],
                  "assetKey": look.get("assetKey"), "scale": scale if look.get("assetKey") else None,
                  "fitChecked": bool(look.get("assetKey")) and scale is not None, "stage": stages[kind],
                  "role": planned["role"], "note": note}
        if look["status"] != planned["status"]:
            record["planned"] = planned["status"]
            record["plannedAssetKey"] = key
        kinds.append(record)
    totals = {"kinds": len(kinds)}
    for status in ("exact", "substitute", "standin"):
        totals[status] = sum(1 for k in kinds if k["status"] == status)
    placed_totals = {s: sum(k["placements"] for k in kinds if k["status"] == s) for s in ("exact", "substitute", "standin")}
    by_tier = {}
    for tier in range(1, 7):
        row = {s: sum(1 for k in kinds if k["tier"] == tier and k["status"] == s) for s in ("exact", "substitute", "standin")}
        by_tier[str(tier)] = row
    build = sorted((k for k in kinds if dress.DRESS[k["id"]]["status"] == "standin" and k["placements"] > 0),
                   key=lambda k: (-k["placements"] * (7 - k["tier"]), k["id"]))
    used = {k.get("assetKey") or k.get("plannedAssetKey") for k in kinds}
    for theme_rows in dress.THEME_ONLY.values():
        for spec in theme_rows.values():
            used.add(spec.get("assetKey") or (catalogue["citykit"][spec["citykit"]]["assetKey"] if "citykit" in spec else None))
    used |= {spec.get("assetKey") for spec in dress.EDGE_DRESS.values()}
    unused = sorted(k for k in catalogue["meshes"] if k.startswith(("ck_", "dt_")) and catalogue["meshes"][k] and k not in used)
    edge = layout.get("edge", {})
    edge_rows = edge.get("rows", [])
    edge_tris = 0
    for row in edge_rows:
        key = dress.EDGE_DRESS[row["kind"]].get("assetKey")
        edge_tris += catalogue["manifest"][key]["triangles"] if key else 12
    data = {
        "stage": dress.CURRENT_STAGE,
        "theme": dress.ACTIVE_THEME,
        "totals": totals,
        "placementsByStatus": placed_totals,
        "byTier": by_tier,
        "kinds": kinds,
        "ownerBuildList": [k["id"] for k in build],
        "unusedKitMeshes": unused,
        "edge": {"parts": len(edge_rows), "triangles": edge_tris, "limits": edge.get("limits", {})},
    }
    json_text = json.dumps(data, indent=1, ensure_ascii=False) + "\n"

    lines = [
        "# Park City coverage report",
        "",
        "GENERATED by `scripts/park_city_world.py` from the dress table `scripts/park_city_dress.py`. Do not edit by hand.",
        "",
        f"Build stage **{dress.CURRENT_STAGE}** ({STAGE_NAMES[dress.CURRENT_STAGE]}), active theme **{dress.ACTIVE_THEME}**. "
        "A kind whose stage is still to come is a stand-in here; its planned mesh is in the Planned column.",
        "",
        "## Totals",
        "",
        "| Status | Kinds | Placements |",
        "| --- | --- | --- |",
    ]
    for status in ("exact", "substitute", "standin"):
        lines.append(f"| {status} | {totals[status]} | {placed_totals[status]} |")
    lines.append(f"| **all** | **{totals['kinds']}** | **{sum(placed_totals.values())}** |")
    lines += ["", "| Tier | Exact | Substitute | Stand-in |", "| --- | --- | --- | --- |"]
    for tier in range(1, 7):
        row = by_tier[str(tier)]
        lines.append(f"| {tier} | {row['exact']} | {row['substitute']} | {row['standin']} |")
    lines += ["", "## Every kind", "",
              "| Kind | Tier | Placed | Stage | Status | Mesh | Scale | Role | Planned | Note |",
              "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for k in sorted(kinds, key=lambda k: (k["tier"], k["id"])):
        planned = f"{k['planned']} `{k['plannedAssetKey']}`" if "planned" in k else ""
        mesh = f"`{k['assetKey']}`" if k["assetKey"] else ""
        scale = "" if k["scale"] is None else f"{k['scale']:g}"
        lines.append(f"| {k['id']} | {k['tier']} | {k['placements']} | {k['stage']} | {k['status']} | {mesh} | {scale} | "
                     f"{k['role']} | {planned} | {k['note']} |")
    lines += ["", "## Owner build list", "",
              "Stand-ins with no mesh yet, placed kinds only, ordered by placements × (7 − tier): the meshes at the top "
              "change the most of the map. The owner picks which ones Blender builds next.", "",
              "| # | Kind | Tier | Placed | Value | Role |", "| --- | --- | --- | --- | --- | --- |"]
    for n, k in enumerate(build, 1):
        lines.append(f"| {n} | {k['id']} | {k['tier']} | {k['placements']} | {k['placements'] * (7 - k['tier'])} | {k['role']} |")
    lines += ["", "## Kit meshes Park City does not use", "",
              f"{len(unused)} uploaded `ck_*` and `dt_*` meshes are not mapped to a kind (catalogue entries the layout has "
              "no object for):", "", ", ".join(f"`{k}`" for k in unused) or "none", "",
              "## Map edge", "",
              f"{len(edge_rows)} scenery Parts, about {edge_tris} triangles (limits: "
              f"{edge.get('limits', {}).get('parts', '-')} Parts, {edge.get('limits', {}).get('triangles', '-')} triangles).",
              ""]
    return json_text, "\n".join(lines)


def generate() -> dict[str, str]:
    layout = json.loads(LAYOUT.read_text())
    catalogue = dress.load_catalogue()
    problems = dress.validate(layout["objects"], catalogue)
    if problems:
        raise SystemExit("dress table (scripts/park_city_dress.py) is invalid:\n  " + "\n  ".join(problems))
    stages = kind_stages(layout)
    objects = build_objects(layout, stages)
    parts, light = split_items(layout, objects)
    summary = layout["summary"]
    if len(parts) != summary["partObjects"] or len(light) != summary["lightObjects"]:
        raise SystemExit(f"layout count mismatch: {len(parts)} parts, {len(light)} light")
    coverage_json, coverage_md = coverage_report(layout, objects, stages, catalogue, parts, light)
    return {
        "world": world_module(layout, objects, parts, catalogue),
        "parts": parts_module(parts, objects),
        "light": light_module(light, objects),
        "strings": strings_module(objects),
        "coverage_json": coverage_json,
        "coverage_md": coverage_md,
    }


def main() -> int:
    check = "--check" in sys.argv[1:]
    generated = generate()
    stale = []
    for key, text in generated.items():
        path = OUT[key]
        if not path.exists() or path.read_text() != text:
            stale.append(path)
            if not check:
                path.write_text(text)
    if check:
        if stale:
            for path in stale:
                print(f"STALE: {path.relative_to(ROOT)} (run python3 scripts/park_city_world.py)")
            return 1
        print("park city world data is up to date")
        return 0
    print("wrote " + ", ".join(p.name for p in OUT.values()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
