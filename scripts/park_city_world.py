def theme_only_objects(objects: list[dict], catalogue: dict) -> dict[str, list[dict]]:
    """Each theme's own objects (THEME_ONLY): a copy of a layout kind with another mesh, or a CityKit meme sized by Park
    City's bulk rule. They are Plaza and core dressing, so they keep a stand-in look until stage 3."""
    base = {o["id"]: o for o in objects}
    dressed = dress.CURRENT_STAGE >= 3
    out: dict[str, list[dict]] = {}
    for theme in dress.SUPPORTED_THEMES:
        rows = []
        for oid, spec in dress.THEME_ONLY.get(theme, {}).items():
            if "copyOf" in spec:
                source = base[spec["copyOf"]]
                row = {k: source[k] for k in ("tier", "size", "coins", "dims", "bulk", "solid", "light")}
                row.update({"id": oid, "bookId": f"park.{oid}", "nameKey": f"object.park.{oid}", "icon": "cube",
                            "assetKey": spec.get("assetKey") if dressed else None,
                            "fallback": spec.get("fallback", "Block"), "role": spec["role"]})
            else:
                kit = catalogue["citykit"][spec["citykit"]]
                dims = kit["dims"]
                bulk = bulk_of(dims)
                tier = tier_of_bulk(bulk)
                row = {"id": oid, "tier": tier, "size": max(dims), "coins": COINS_BY_TIER[tier - 1],
                       "bookId": f"park.{oid}", "nameKey": kit["nameKey"], "icon": "cube",
                       "assetKey": kit["assetKey"] if dressed else None, "fallback": kit.get("fallback") or "Block",
                       "role": kit["role"], "atlas": kit.get("atlas") if dressed else None, "dims": dims,
                       "bulk": r2(bulk), "light": True if tier <= 2 else None}
            rows.append(dict(sorted(row.items(), key=lambda kv: OBJECT_FIELD_ORDER.index(kv[0]))))
        out[theme] = rows
    return out


OBJECT_FIELD_ORDER = ["id", "tier", "size", "coins", "bookId", "nameKey", "icon", "assetKey", "fallback", "role",
                      "atlas", "shade", "dims", "bulk", "solid", "light"]


def meme_rows(layout) -> tuple[list[dict], list[dict]]:
    """The layout's meme spots: slot spots become base fixed placements, the rest overlays in every theme."""
    slots, plain = [], []
    for index, spot in enumerate(layout.get("memes", []), 1):
        row = {"id": f"meme_{index}", "objectId": spot.get("slot") or spot["object"], "x": r2(spot["x"]),
               "y": r2(spot.get("y", 0)), "z": r2(spot["z"]), "yaw": round(math.radians(spot.get("yaw", 0)), 3)}
        (slots if "slot" in spot else plain).append(row)
    return slots, plain


def theme_bindings(objects: list[dict], catalogue: dict, layout) -> dict:
    own = theme_only_objects(objects, catalogue)
    _, plain = meme_rows(layout)
    tiers = {o["id"]: o["tier"] for o in objects}
    bindings = {}
    for theme in dress.SUPPORTED_THEMES:
        for row in own[theme]:
            tiers.setdefault(row["id"], row["tier"])
        for slot, target in dress.SLOT_BINDINGS[theme].items():
            mine = {r["id"]: r["tier"] for r in own[theme]}
            tier = mine.get(target, tiers.get(target))
            if tier != SLOT_TIERS[slot]:
                raise SystemExit(f"{theme} {slot} is tier {SLOT_TIERS[slot]} but {target} is tier {tier}")
        for row in plain:
            if row["objectId"] not in {r["id"] for r in own[theme]}:
                raise SystemExit(f"meme {row['id']} places {row['objectId']}, which is not a {theme} theme-only object")
        bindings[theme] = {
            "slots": dict(dress.SLOT_BINDINGS[theme]),
            "overlays": {"zones": [], "fixedPlacements": plain},
            "heroVariants": {},
            "objects": own[theme],
        }
    return bindings


def slot_rows(parts) -> dict[str, str]:
    """Parts rows that are theme slots: the Plaza landmark (the layout's theme_landmark) is slot.landmark."""
    rows = {}
    for index, part in enumerate(parts, 1):
        if part["group"] == "theme_landmark":
            rows[f"p{index}"] = "slot.landmark"
    if len(rows) != 1:
        raise SystemExit(f"expected one theme_landmark placement, found {len(rows)}")
    return rows


def build_scenery(layout) -> list[dict]:
    """The map-edge band (R-10): anchored scenery, never collided with, queried or eaten. Built by WorldBuilder."""
    out = []
    for row in layout.get("edge", {}).get("rows", []):
        look = dress.EDGE_DRESS[row["kind"]]
        w, h, d = row["size"]
        out.append({
            "id": row["id"],
            "assetKey": look.get("assetKey"),
            "role": look["role"],
            "cframe": {"x": r2(row["x"]), "y": r2(row.get("y", 0) + h / 2), "z": r2(row["z"]), "yaw": row.get("yaw", 0)},
            "size": {"x": r2(w), "y": r2(h), "z": r2(d)},
        })
    return out


def find_landmark(layout, name):
    for landmark in layout["landmarks"]:
        if landmark["id"] == name:
            return landmark
    raise SystemExit(f"landmark {name} not found")


def build_shots(layout) -> list[dict]:
    spawn = {s["id"]: s for s in layout["spawns"]}
    oak = find_landmark(layout, "giant_oak")
    ferris = find_landmark(layout, "ferris_wheel")
    car_park = find_landmark(layout, "car_park")
    pond = next(w for w in layout["water"] if w["id"] == "pond")
    pond_x, pond_z = pond["ellipse"][0], pond["ellipse"][1]
    maze = layout["maze"]
    maze_cx = maze["origin"][0] + len(maze["rows"]) * maze["cell"] / 2
    maze_cz = maze["origin"][1] + len(maze["rows"]) * maze["cell"] / 2
    roofs = layout["roofRun"]["roofs"]
    roof_x = (roofs[0]["x"] + roofs[-1]["x"]) / 2
    shots = [
        ("spawn_nw", [spawn["spawn_01"]["x"], 2.5, spawn["spawn_01"]["z"]], [oak["x"], 6, oak["z"]]),
        ("spawn_ne", [spawn["spawn_04"]["x"], 2.5, spawn["spawn_04"]["z"]], [pond_x, 2, pond_z]),
        ("spawn_se", [spawn["spawn_07"]["x"], 2.5, spawn["spawn_07"]["z"]], [ferris["x"], 20, ferris["z"]]),
        ("spawn_sw", [spawn["spawn_10"]["x"], 2.5, spawn["spawn_10"]["z"]], [maze_cx, 2, maze_cz]),
        ("duck_island", [pond_x - 90, 30, pond_z + 80], [pond_x, 1, pond_z]),
        ("hedge_maze", [maze_cx + 70, 70, maze_cz + 110], [maze_cx, 0, maze_cz]),
        ("roof_run", [roof_x, 45, -140], [roof_x, roofs[0]["y"], -232]),
        ("car_park", [car_park["x"] - 90, 55, car_park["z"] + 100], [car_park["x"], 10, car_park["z"]]),
        ("plaza", [0, 40, 110], [0, 5, 0]),
        ("giant_oak", [oak["x"] + 70, 35, oak["z"] + 70], [oak["x"], 15, oak["z"]]),
        ("overview", [0, 600, 480], [0, 0, 0]),
    ]
    return [{"name": n, "pos": [r2(v) for v in pos], "look": [r2(v) for v in look], "fov": SHOT_FOV}
            for n, pos, look in shots]


