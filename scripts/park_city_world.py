def strings_module(objects) -> str:
    entries = {}
    for index, (en, es) in enumerate(TIER_NAMES, 1):
        entries[f"tier.park.{index}.name"] = {"en": en, "es": es}
        entries[f"tier.park.{index}.headline"] = {"en": TIER_HEADLINES[index - 1][0], "es": TIER_HEADLINES[index - 1][1]}
    for obj in objects:
        kind = obj["id"]
        if kind not in ES:
            raise SystemExit(f"no Spanish name for {kind}")
        entries[f"object.park.{kind}"] = {"en": english_name(kind), "es": ES[kind]}
    return (
        HEADER
        + "-- Names of the Park City kinds and tiers. The Spanish names are a first pass for owner review\n"
        + "-- (docs/release-candidate.md). Merged into Strings.luau.\n"
        + "--!nonstrict\n\n"
        + "return " + lua(entries) + "\n"
    )


def generate() -> dict[str, str]:
    layout = json.loads(LAYOUT.read_text())
    objects = build_objects(layout)
    parts, light = split_items(layout, objects)
    summary = layout["summary"]
    if len(parts) != summary["partObjects"] or len(light) != summary["lightObjects"]:
        raise SystemExit(f"layout count mismatch: {len(parts)} parts, {len(light)} light")
    return {
        "world": world_module(layout, objects),
        "parts": parts_module(parts, objects),
        "light": light_module(light, objects),
        "strings": strings_module(objects),
    }


def main() -> int:
    check = "--check" in sys.argv[1:]
    generated = generate()
    stale = []
    for key, text in generated.items():
        path = OUT[key]
        if not path.exists() or path.read_text() != text:
            stale.append(path)
            if not check:
                path.write_text(text)
    if check:
        if stale:
            for path in stale:
                print(f"STALE: {path.relative_to(ROOT)} (run python3 scripts/park_city_world.py)")
            return 1
        print("park city world data is up to date")
        return 0
    print("wrote " + ", ".join(p.name for p in OUT.values()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
