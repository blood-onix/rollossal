# --- Luau writer ---------------------------------------------------------------------------------------------
def num(value: float) -> str:
    if isinstance(value, bool):
        raise TypeError("bool is not a number")
    if float(value).is_integer():
        return str(int(value))
    text = f"{value:.4f}".rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


def lua(value, indent: int = 0) -> str:
    pad = "\t" * indent
    inner = "\t" * (indent + 1)
    if value is None:
        return "nil"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return num(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, (list, tuple)):
        if all(isinstance(v, (int, float)) and not isinstance(v, bool) for v in value):
            return "{ " + ", ".join(num(v) for v in value) + " }" if value else "{}"
        if not value:
            return "{}"
        return "{\n" + "".join(f"{inner}{lua(v, indent + 1)},\n" for v in value) + pad + "}"
    if isinstance(value, dict):
        if not value:
            return "{}"
        lines = []
        for key, item in value.items():
            if item is None:
                continue
            name = key if key.isidentifier() and key not in LUA_KEYWORDS else f"[{json.dumps(key)}]"
            lines.append(f"{inner}{name} = {lua(item, indent + 1)},\n")
        return "{\n" + "".join(lines) + pad + "}"
    raise TypeError(f"cannot write {type(value)}")


LUA_KEYWORDS = {"and", "break", "do", "else", "elseif", "end", "false", "for", "function", "if", "in", "local",
                "nil", "not", "or", "repeat", "return", "then", "true", "until", "while", "continue", "type"}


def r2(value: float) -> float:
    return round(value + 0.0, 2) + 0.0


# --- Derived data ---------------------------------------------------------------------------------------------
def bulk_of(dims) -> float:
    return (dims[0] * dims[1] * dims[2]) ** (1 / 3)


def tier_of_bulk(bulk: float) -> int:
    """The layout's tier rule: by bulk, inclusive at the top (a bulk of exactly 3 is Tier 2)."""
    need = 2 * bulk - 1e-6
    tier = 1
    for index, minimum in enumerate(TIER_MIN, 1):
        if minimum <= need:
            tier = index
    return tier


def build_objects(layout) -> list[dict]:
    solid_kinds = set()
    for scene in layout["scenes"]:
        for item in scene["items"]:
            if item.get("solid"):
                solid_kinds.add(item["object"])
    for landmark in layout["landmarks"]:
        if landmark.get("solid"):
            solid_kinds.add(landmark["object"])
    objects = []
    for kind in sorted(layout["objects"]):
        record = layout["objects"][kind]
        dims = record["dims"]
        bulk = bulk_of(dims)
        tier = record["tier"]
        entry = {
            "id": kind,
            "tier": tier,
            "size": max(dims),
            "coins": COINS_BY_TIER[tier - 1],
            "bookId": f"park.{kind}",
            "nameKey": f"object.park.{kind}",
            "icon": "cube",
            "fallback": "Block",
            "dims": dims,
            "bulk": r2(bulk) if r2(bulk) > 0 else round(bulk, 4),
            "solid": True if kind in solid_kinds else None,
            "light": True if tier <= 2 else None,
        }
        objects.append(entry)
    return objects


def build_tiers() -> list[dict]:
    tiers = []
    for index, minimum in enumerate(TIER_MIN, 1):
        top = TIER_MIN[index] if index < len(TIER_MIN) else TIER_TOP
        tiers.append({
            "tier": index,
            "nameKey": f"tier.park.{index}.name",
            "minDiameter": minimum,
            "maxDiameter": top,
            "headlineKey": f"tier.park.{index}.headline",
            "headlineIcon": "cube",
        })
    return tiers


def build_blocks(layout) -> list[dict]:
    blocks = []
    ordered = sorted(layout["blocks"], key=lambda b: (b["id"] not in BLOCK_ORDER_FIRST, 0))
    for block in ordered:
        x0, z0, x1, z1 = block["rect"]
        y0, y1 = block["y"]
        width, depth, height = x1 - x0, z1 - z0, y1 - y0
        entry = {
            "id": block["id"],
            "kind": "Block",
            "cframe": {"x": r2((x0 + x1) / 2), "y": r2((y0 + y1) / 2), "z": r2((z0 + z1) / 2), "yaw": 0},
            "size": {"x": r2(width), "y": r2(height), "z": r2(depth)},
            "swatch": block["kind"] if block["kind"] in PALETTE else "stone",
        }
        kind = block["kind"]
        if kind == "wall":
            entry["kind"] = "Boundary"
            entry.pop("swatch")
            entry["swatch"] = "stone"
        elif kind == "ramp":
            up = block.get("up")
            if up not in UP_YAW:
                raise SystemExit(f"ramp {block['id']} has no usable 'up' side")
            yaw = UP_YAW[up]
            entry["kind"] = "Wedge"
            entry["cframe"]["yaw"] = yaw
            # Wedge size is (width, rise, run); at yaw 90 or 270 the run lies along world X.
            if yaw in (90, 270):
                entry["size"] = {"x": r2(depth), "y": r2(height), "z": r2(width)}
        elif kind == "spiral":
            entry["kind"] = "Spiral"
            entry["turns"] = block.get("turns", 2)
            entry["width"] = block.get("width", 8)
        blocks.append(entry)
    return blocks


def build_spawns(layout) -> list[dict]:
    spawns = []
    for index, spawn in enumerate(layout["spawns"], 1):
        spawns.append({"slot": index, "x": spawn["x"], "y": 0, "z": spawn["z"], "yaw": round(spawn["facing"])})
    return spawns


def all_items(layout):
    """Every object in layout order: (group id, item) with scene items, then trail items, then landmarks."""
    for scene in layout["scenes"]:
        for item in scene["items"]:
            yield scene["id"], item
    for trail in layout["trails"]:
        for item in trail["items"]:
            yield trail["id"], item
    for landmark in layout["landmarks"]:
        yield landmark["id"], landmark


def split_items(layout, objects):
    tier_of = {o["id"]: o["tier"] for o in objects}
    parts, light = [], []
    for group, item in all_items(layout):
        kind = item["object"]
        record = {"group": group, "kind": kind, "x": item["x"], "y": item.get("y", 0), "z": item["z"],
                  "yaw": item.get("yaw", 0)}
        (light if tier_of[kind] <= 2 else parts).append(record)
    return parts, light


def parts_module(parts, objects) -> str:
    solid = {o["id"] for o in objects if o.get("solid")}
    rows = []
    for index, part in enumerate(parts, 1):
        row = {"id": f"p{index}", "objectId": part["kind"], "x": r2(part["x"]), "y": r2(part["y"]),
               "z": r2(part["z"]), "yaw": round(math.radians(part["yaw"]), 3)}
        if part["kind"] in solid:
            row["solid"] = True
        rows.append(row)
    return HEADER + "-- The Tier 3 to 6 placements of Park City: server Parts, ids p<n> in layout order.\n--!nonstrict\n\n" + \
        "local rows = " + lua(rows) + "\n\nreturn rows\n"


def light_module(light, objects) -> str:
    kinds = sorted({row["kind"] for row in light})
    kind_index = {kind: i for i, kind in enumerate(kinds, 1)}
    data_lines = []
    ranges: dict[str, list[int]] = {}
    for index, row in enumerate(light, 1):
        data_lines.append("\t" + ", ".join([
            str(kind_index[row["kind"]]), num(r2(row["x"])), num(r2(row["y"])), num(r2(row["z"])),
            num(round(math.radians(row["yaw"]), 3)),
        ]) + ",")
        group = row["group"]
        if group.startswith("doorstep_") or (group.startswith("trail_") and int(group[6:]) <= 12):
            span = ranges.setdefault(group, [index, index])
            span[1] = index
    ranges_text = lua({k: v for k, v in ranges.items()})
    return (
        HEADER
        + "-- The Tier 1 and 2 objects of Park City as data. Row i is the light id \"L\"..i: five numbers (kind index,\n"
        + "-- x, y, z, yaw in radians). `ranges` holds the first and last row of each spawn's doorstep and spawn trail.\n"
        + "--!nonstrict\n\nlocal kinds = " + lua(kinds) + "\n\n"
        + "local ranges = " + ranges_text + "\n\n"
        + "local data = {\n" + "\n".join(data_lines) + "\n}\n\n"
        + "return { stride = 5, count = " + str(len(light)) + ", kinds = kinds, ranges = ranges, data = data }\n"
    )


